/** Comma-separated hex list ttfx wants, or nothing if the theme is unknown. */
export function themePaletteArg(id: string): string | undefined {
  if (!Object.hasOwn(THEME_PALETTES, id)) return undefined
  return THEME_PALETTES[id].join(',')
}
